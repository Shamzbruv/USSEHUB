import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {authEmails, renderAuthEmail} from './email-templates.mjs';
import {corporateEmail} from '../supabase/functions/_shared/email.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
function output(relative, content) {
  const filename = path.join(root,relative);
  if (check) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename,'utf8') !== content) throw new Error(`Generated email source is stale: ${relative}`);
  } else {
    fs.mkdirSync(path.dirname(filename),{recursive:true});
    fs.writeFileSync(filename,content);
  }
}
for (const email of authEmails) output(`supabase/templates/${email.key}.html`,renderAuthEmail(email)+'\n');
const localSections=authEmails.map(email => {
  const type=email.security ? 'notification' : 'template';
  const key=email.security ? email.key.replace(/_notification$/,'') : email.key;
  return `[auth.email.${type}.${key}]\n${email.security ? 'enabled = false\n' : ''}subject = ${JSON.stringify(email.subject)}\ncontent_path = "./supabase/templates/${email.key}.html"`;
}).join('\n\n');
const localConfig=fs.readFileSync(path.join(root,'supabase/config.toml'),'utf8').replace(/# BEGIN USSE EMAIL BRANDING[^]*?# END USSE EMAIL BRANDING/,
  `# BEGIN USSE EMAIL BRANDING (generated by npm run build:emails)\n# Local security notification flags mirror the current hosted configuration.\n${localSections}\n# END USSE EMAIL BRANDING`);
output('supabase/config.toml',localConfig);

// Render the same table-based design inside Postgres. Only escaped content is
// passed to format(); user content can never become markup or a destination URL.
let layout = corporateEmail({title:'__USSE_TITLE__',preheader:'__USSE_PREHEADER__',bodyHtml:'__USSE_BODY__',actionLabel:'__USSE_ACTION__',actionUrl:'https://ussehub.com/__USSE_ROUTE__',note:'Sign in to your workspace to review this update. Need assistance? Contact info@ussehub.com.'});
layout = layout.replaceAll('%','%%');
for (const [marker,slot] of Object.entries({TITLE:1,PREHEADER:2,BODY:3,ACTION:4,ROUTE:5})) layout=layout.replaceAll(`__USSE_${marker}__`,`%${slot}$s`);
const baseline = fs.readFileSync(path.join(root,'supabase/migrations/20260728000000_advertising_workflow_repair.sql'),'utf8');
const processor = baseline.slice(baseline.indexOf('CREATE OR REPLACE FUNCTION private.process_ad_notification_outbox('),baseline.indexOf('CREATE OR REPLACE FUNCTION private.trigger_ad_notification_dispatch()'))
  .replace("'text', v_row.text_body", "'text', v_row.text_body,\n          'html', private.render_notification_email(v_row.subject, v_row.text_body, v_row.template_key)");
output('supabase/migrations/20261027180752_corporate_email_branding.sql',`-- Generated by npm run build:emails. Review and commit before deployment.
-- Adds HTML to every outbox event, including future template keys, while
-- preserving the plain-text alternative, recipients and existing queue behavior.
CREATE OR REPLACE FUNCTION private.email_html_escape(p_value text)
RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE SECURITY INVOKER SET search_path = ''
AS $escape$
  SELECT replace(replace(replace(replace(replace(coalesce(p_value,''), '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;'), chr(39), '&#39;');
$escape$;

CREATE OR REPLACE FUNCTION private.render_notification_email(p_subject text, p_body text, p_template_key text)
RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE SECURITY INVOKER SET search_path = ''
AS $render$
  SELECT format($email$${layout}$email$,
    private.email_html_escape(p_subject),
    private.email_html_escape(left(p_body,160)),
    '<p style="margin:0;word-break:break-word;overflow-wrap:anywhere;">' || replace(private.email_html_escape(p_body), E'\\n', '<br>') || '</p>',
    CASE WHEN p_template_key LIKE '%admin%' THEN 'Open admin workspace' ELSE 'Open your AJM workspace' END,
    CASE WHEN p_template_key LIKE '%admin%' THEN 'ajm-admin-panel' ELSE 'ajm-advertising-hub' END
  );
$render$;

REVOKE ALL ON FUNCTION private.email_html_escape(text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION private.render_notification_email(text,text,text) FROM PUBLIC, anon, authenticated;

${processor}`);
console.log(`${check ? 'Verified' : 'Built'} ${authEmails.length} Auth templates and the shared SQL notification design.`);
