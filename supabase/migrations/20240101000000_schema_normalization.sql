-- 8. Listing Status History
CREATE TABLE IF NOT EXISTS listing_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id uuid REFERENCES listings(id) ON DELETE CASCADE,
    old_status text,
    new_status text,
