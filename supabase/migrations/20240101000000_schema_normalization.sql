CREATE INDEX IF NOT EXISTS listings_search_document_idx ON listings USING gin (search_document);

-- Update search_document trigger instead of generated column so it can be managed with coalesce
CREATE OR REPLACE FUNCTION update_search_document() RETURNS TRIGGER AS $$
BEGIN
    NEW.search_document := to_tsvector('english',
        coalesce(NEW.business_name, '') || ' ' ||
        coalesce(NEW.description, '') || ' ' ||
        coalesce(NEW.parish, '') || ' ' ||
        coalesce(NEW.location_display, '')
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_update_search_document ON listings;
CREATE TRIGGER trg_update_search_document
    BEFORE INSERT OR UPDATE ON listings
    FOR EACH ROW EXECUTE PROCEDURE update_search_document();

-- ============================================
-- PRIVATE HELPERS & RLS ENFORCEMENT
-- ============================================

CREATE SCHEMA IF NOT EXISTS private;

CREATE OR REPLACE FUNCTION private.is_admin(p_uid uuid DEFAULT auth.uid())
RETURNS boolean AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.profiles 
        WHERE id = p_uid AND role = 'admin'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';

CREATE OR REPLACE FUNCTION private.has_active_membership(p_uid uuid DEFAULT auth.uid())
RETURNS boolean AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.memberships 
        WHERE user_id = p_uid AND status = 'active'
        AND (ends_at IS NULL OR ends_at > now())
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';

