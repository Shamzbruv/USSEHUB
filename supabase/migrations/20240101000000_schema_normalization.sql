USING (
    created_by = (SELECT auth.uid())
    OR private.is_admin((SELECT auth.uid()))
    -- Public media reading will be via signed URLs or bucket policy directly, not table read.
);

DROP POLICY IF EXISTS "Users insert own media" ON listing_media;
CREATE POLICY "Users insert own media" ON listing_media FOR INSERT
WITH CHECK (created_by = (SELECT auth.uid()));

-- Status History
DROP POLICY IF EXISTS "History viewable by owner or admin" ON listing_status_history;
CREATE POLICY "History viewable by owner or admin" ON listing_status_history FOR SELECT
USING (
    EXISTS (SELECT 1 FROM listings l WHERE l.id = listing_id AND l.owner_user_id = (SELECT auth.uid()))
    OR private.is_admin((SELECT auth.uid()))
);

