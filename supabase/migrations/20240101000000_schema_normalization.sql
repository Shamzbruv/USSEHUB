-- Profiles: Own row, Admin full
DROP POLICY IF EXISTS "Profiles viewable by owner or admin" ON profiles;
CREATE POLICY "Profiles viewable by owner or admin" ON profiles FOR SELECT
USING (id = (SELECT auth.uid()) OR private.is_admin((SELECT auth.uid())));

DROP POLICY IF EXISTS "Profiles updatable by owner or admin" ON profiles;
CREATE POLICY "Profiles updatable by owner or admin" ON profiles FOR UPDATE
USING (id = (SELECT auth.uid()) OR private.is_admin((SELECT auth.uid())));

-- Plans: Public read, Admin full
DROP POLICY IF EXISTS "Active plans viewable by public" ON membership_plans;
CREATE POLICY "Active plans viewable by public" ON membership_plans FOR SELECT
USING (is_active = true OR private.is_admin((SELECT auth.uid())));

-- Memberships: Owner read, Admin full
DROP POLICY IF EXISTS "Memberships viewable by owner or admin" ON memberships;
CREATE POLICY "Memberships viewable by owner or admin" ON memberships FOR SELECT
USING (user_id = (SELECT auth.uid()) OR private.is_admin((SELECT auth.uid())));

-- Category Groups & Options: Public read
DROP POLICY IF EXISTS "Category groups viewable by public" ON category_groups;
CREATE POLICY "Category groups viewable by public" ON category_groups FOR SELECT
USING (is_active = true OR private.is_admin((SELECT auth.uid())));

DROP POLICY IF EXISTS "Category options viewable by public" ON category_options;
CREATE POLICY "Category options viewable by public" ON category_options FOR SELECT
USING (is_active = true OR private.is_admin((SELECT auth.uid())));

-- Listings
DROP POLICY IF EXISTS "Approved listings are public" ON listings;
CREATE POLICY "Approved listings are public" ON listings FOR SELECT
USING (
    (status = 'approved' AND (expires_at IS NULL OR expires_at > now()) AND (published_at IS NULL OR published_at <= now()))
    OR owner_user_id = (SELECT auth.uid())
    OR private.is_admin((SELECT auth.uid()))
);

DROP POLICY IF EXISTS "Users insert own listings" ON listings;
CREATE POLICY "Users insert own listings" ON listings FOR INSERT
WITH CHECK (owner_user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Users update editable listings" ON listings;
CREATE POLICY "Users update editable listings" ON listings FOR UPDATE
USING (
    (owner_user_id = (SELECT auth.uid()) AND status IN ('draft','pending','changes_requested'))
    OR private.is_admin((SELECT auth.uid()))
);

-- Listing Media
