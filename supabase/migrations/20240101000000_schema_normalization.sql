-- 1. Create EXTENSION for text search
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- 2. Modify Profiles
ALTER TABLE profiles 
ADD COLUMN IF NOT EXISTS account_status text DEFAULT 'active' CHECK (account_status IN ('active','disabled')),
ADD COLUMN IF NOT EXISTS updated_at timestamptz DEFAULT now();

-- Ensure roles are correctly constrained
ALTER TABLE profiles DROP CONSTRAINT IF EXISTS profiles_role_check;
ALTER TABLE profiles ADD CONSTRAINT profiles_role_check CHECK (role IN ('admin','member','subscriber'));

-- 3. Membership Plans
CREATE TABLE IF NOT EXISTS membership_plans (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    code text UNIQUE NOT NULL,
    name text NOT NULL,
    member_stats_access boolean DEFAULT false,
    price_amount numeric,
    billing_interval text,
    is_active boolean DEFAULT true,
    created_at timestamptz DEFAULT now()
);

-- 4. Memberships
CREATE TABLE IF NOT EXISTS memberships (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid REFERENCES profiles(id) ON DELETE CASCADE,
    plan_id uuid REFERENCES membership_plans(id),
    status text CHECK (status IN ('pending','active','inactive','expired','cancelled','past_due')),
    starts_at timestamptz,
    ends_at timestamptz,
    source text,
    provider text,
    provider_customer_id text,
    provider_subscription_id text,
    metadata jsonb,
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now()
);

-- 5. Taxonomy (Category Groups & Options)
CREATE TABLE IF NOT EXISTS category_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text UNIQUE NOT NULL,
    name text NOT NULL,
    sort_order int DEFAULT 0,
    is_active boolean DEFAULT true
);

CREATE TABLE IF NOT EXISTS category_options (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint REFERENCES category_groups(id) ON DELETE CASCADE,
    slug text NOT NULL,
    name text NOT NULL,
    search_aliases text[],
    sort_order int DEFAULT 0,
    is_active boolean DEFAULT true,
    UNIQUE(group_id, slug)
);

-- 6. Modify Listings
-- Safely handle renames and additions
DO $$
BEGIN
    -- Rename user_id to owner_user_id if owner_user_id doesn't exist
    IF EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='listings' AND column_name='user_id') AND
       NOT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='listings' AND column_name='owner_user_id') THEN
        ALTER TABLE listings RENAME COLUMN user_id TO owner_user_id;
    END IF;
    
    -- Rename phone to contact_phone if it exists
    IF EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='listings' AND column_name='phone') AND
       NOT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='listings' AND column_name='contact_phone') THEN
        ALTER TABLE listings RENAME COLUMN phone TO contact_phone;
    END IF;
END $$;

ALTER TABLE listings 
ADD COLUMN IF NOT EXISTS slug text UNIQUE,
ADD COLUMN IF NOT EXISTS category_group_id bigint REFERENCES category_groups(id),
