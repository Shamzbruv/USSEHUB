-- Update the check constraint for status
ALTER TABLE listings DROP CONSTRAINT IF EXISTS listings_status_check;
ALTER TABLE listings ADD CONSTRAINT listings_status_check CHECK (status IN ('draft','pending','changes_requested','approved','rejected','expired','archived'));

-- 7. Listing Media
